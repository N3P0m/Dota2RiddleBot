function genericPoetic(hero: Hero): string {
  const role = hero.roles[0] ?? "герой";
  return `В дыму сражения шепчут его имя лишь те, кто видел ${role.toLowerCase()} на линии. Заклинания оставляют след — узнай героя по судьбе битвы, не по словам. (Тестовая загадка)`;
}

export function getPresetRiddle(hero: Hero): string {
  const pool = BY_HERO_ID[hero.id];
  if (pool?.length) {
    return pool[Math.floor(Math.random() * pool.length)]!;
  }
  return genericPoetic(hero);
}
